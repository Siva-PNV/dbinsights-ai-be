CREATE TABLE IF NOT EXISTS app_user (
  user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(30) NOT NULL DEFAULT 'USER',
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS password_reset_token (
  token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  consumed_at TIMESTAMP WITH TIME ZONE NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_password_reset_user FOREIGN KEY (user_id) REFERENCES app_user(user_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_password_reset_user_created
  ON password_reset_token (user_id, created_at);

CREATE TABLE IF NOT EXISTS email_verification_token (
  token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  verified_at TIMESTAMP WITH TIME ZONE NULL,
  CONSTRAINT fk_email_verification_user FOREIGN KEY (user_id) REFERENCES app_user(user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS monitored_database (
  database_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  database_name VARCHAR(120) NOT NULL,
  db_type VARCHAR(30) NOT NULL,
  host VARCHAR(255) NOT NULL,
  port INT NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_database_user FOREIGN KEY (user_id) REFERENCES app_user(user_id)
);

CREATE TABLE IF NOT EXISTS monitored_database_credential (
  database_id BIGINT PRIMARY KEY,
  encrypted_credentials TEXT NOT NULL,
  CONSTRAINT fk_credential_database FOREIGN KEY (database_id) REFERENCES monitored_database(database_id)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS table_metadata (
  table_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  database_id BIGINT NOT NULL,
  table_name VARCHAR(190) NOT NULL,
  row_count BIGINT NOT NULL DEFAULT 0,
  table_size BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT fk_table_database FOREIGN KEY (database_id) REFERENCES monitored_database(database_id),
  CONSTRAINT uq_database_table UNIQUE (database_id, table_name)
);

CREATE TABLE IF NOT EXISTS column_metadata (
  column_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_id BIGINT NOT NULL,
  column_name VARCHAR(190) NOT NULL,
  data_type VARCHAR(120) NOT NULL,
  is_nullable BOOLEAN NOT NULL DEFAULT TRUE,
  ordinal_position INT NOT NULL,
  CONSTRAINT fk_column_table FOREIGN KEY (table_id) REFERENCES table_metadata(table_id),
  CONSTRAINT uq_table_column UNIQUE (table_id, column_name)
);

CREATE TABLE IF NOT EXISTS index_metadata (
  index_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_id BIGINT NOT NULL,
  index_name VARCHAR(190) NOT NULL,
  index_type VARCHAR(60) NOT NULL,
  is_unique BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT fk_index_table FOREIGN KEY (table_id) REFERENCES table_metadata(table_id),
  CONSTRAINT uq_table_index UNIQUE (table_id, index_name)
);

CREATE TABLE IF NOT EXISTS index_column (
  index_id BIGINT NOT NULL,
  column_id BIGINT NOT NULL,
  column_order INT NOT NULL,
  PRIMARY KEY (index_id, column_id),
  CONSTRAINT fk_index_column_index FOREIGN KEY (index_id) REFERENCES index_metadata(index_id),
  CONSTRAINT fk_index_column_column FOREIGN KEY (column_id) REFERENCES column_metadata(column_id)
);

CREATE TABLE IF NOT EXISTS monitored_query (
  query_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  database_id BIGINT NOT NULL,
  query_text TEXT NOT NULL,
  query_hash VARCHAR(128) NOT NULL,
  first_seen TIMESTAMP WITH TIME ZONE NOT NULL,
  last_seen TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_query_database FOREIGN KEY (database_id) REFERENCES monitored_database(database_id),
  CONSTRAINT uq_database_query_hash UNIQUE (database_id, query_hash)
);

CREATE TABLE IF NOT EXISTS query_performance (
  performance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  query_id BIGINT NOT NULL,
  execution_time DECIMAL(14,3) NOT NULL,
  execution_count BIGINT NOT NULL DEFAULT 1,
  rows_examined BIGINT NOT NULL DEFAULT 0,
  rows_returned BIGINT NOT NULL DEFAULT 0,
  recorded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_performance_query FOREIGN KEY (query_id) REFERENCES monitored_query(query_id)
);

CREATE TABLE IF NOT EXISTS telemetry_snapshot (
  snapshot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  database_id BIGINT NULL,
  database_name VARCHAR(120) NOT NULL,
  available BOOLEAN NOT NULL DEFAULT FALSE,
  message TEXT NOT NULL,
  collected_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  slow_query_threshold_ms BIGINT NOT NULL DEFAULT 500,
  internal_query_count INT NOT NULL DEFAULT 0,
  internal_queries_included BOOLEAN NOT NULL DEFAULT FALSE,
  query_count INT NOT NULL DEFAULT 0,
  demo_data BOOLEAN NOT NULL DEFAULT FALSE,
  digest_summary TEXT NOT NULL,
  CONSTRAINT fk_snapshot_database FOREIGN KEY (database_id) REFERENCES monitored_database(database_id)
);

CREATE TABLE IF NOT EXISTS schema_issue (
  issue_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_id BIGINT NOT NULL,
  issue_type VARCHAR(80) NOT NULL,
  description TEXT NOT NULL,
  severity VARCHAR(20) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
  detected_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_issue_table FOREIGN KEY (table_id) REFERENCES table_metadata(table_id)
);

CREATE TABLE IF NOT EXISTS health_score (
  health_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  database_id BIGINT NOT NULL,
  query_score DECIMAL(5,2) NULL,
  index_score DECIMAL(5,2) NOT NULL,
  schema_score DECIMAL(5,2) NOT NULL,
  metadata_score DECIMAL(5,2) NOT NULL,
  overall_score DECIMAL(5,2) NOT NULL,
  calculated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_health_database FOREIGN KEY (database_id) REFERENCES monitored_database(database_id)
);

CREATE TABLE IF NOT EXISTS recommendation (
  recommendation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  database_id BIGINT NOT NULL,
  issue_id BIGINT NULL,
  recommendation_text TEXT NOT NULL,
  reason TEXT NOT NULL,
  severity VARCHAR(20) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'PENDING_REVIEW',
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_recommendation_database FOREIGN KEY (database_id) REFERENCES monitored_database(database_id),
  CONSTRAINT fk_recommendation_issue FOREIGN KEY (issue_id) REFERENCES schema_issue(issue_id)
);

CREATE TABLE IF NOT EXISTS alert_rule (
  rule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rule_name VARCHAR(180) NOT NULL,
  metric VARCHAR(120) NOT NULL,
  comparison_operator VARCHAR(10) NOT NULL DEFAULT '>',
  threshold_value DOUBLE PRECISION NOT NULL,
  severity VARCHAR(20) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS alert_event (
  event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rule_id BIGINT NOT NULL,
  metric_value DOUBLE PRECISION NOT NULL,
  severity VARCHAR(20) NOT NULL,
  state VARCHAR(30) NOT NULL DEFAULT 'OPEN',
  message TEXT NOT NULL,
  occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_alert_event_rule FOREIGN KEY (rule_id) REFERENCES alert_rule(rule_id)
);