package edu.dbinsight.analysis;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import edu.dbinsight.api.ApiModels.LiveRecommendationResponse;
import edu.dbinsight.api.ApiModels.LiveSchemaSummary;
import edu.dbinsight.api.ApiModels.QueryTelemetry;
import edu.dbinsight.api.ApiModels.RecommendationSummary;
import java.net.http.HttpClient;
import java.time.Duration;
import java.time.Instant;
import java.util.List;
import java.util.Map;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpStatus;
import org.springframework.http.client.JdkClientHttpRequestFactory;
import org.springframework.stereotype.Component;
import org.springframework.web.client.RestClient;
import org.springframework.web.client.RestClientException;
import org.springframework.web.client.RestClientResponseException;

@Component
public class GeminiRecommendationGenerator implements AiRecommendationGenerator {
    private final RestClient restClient;
    private final ObjectMapper objectMapper;
    private final String apiKey;
    private final String model;
    private final boolean enabled;

    public GeminiRecommendationGenerator(
            RestClient.Builder restClientBuilder,
            ObjectMapper objectMapper,
            @Value("${app.ai.gemini.base-url:https://generativelanguage.googleapis.com/v1beta}") String baseUrl,
            @Value("${app.ai.gemini.api-key:}") String apiKey,
            @Value("${app.ai.gemini.model:gemini-3.8-flash}") String model,
            @Value("${app.ai.recommendations.enabled:false}") boolean enabled) {
        HttpClient httpClient = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(5)).build();
        JdkClientHttpRequestFactory requestFactory = new JdkClientHttpRequestFactory(httpClient);
        requestFactory.setReadTimeout(Duration.ofSeconds(45));
        this.restClient = restClientBuilder.baseUrl(baseUrl).requestFactory(requestFactory).build();
        this.objectMapper = objectMapper;
        this.apiKey = apiKey;
        this.model = model;
        this.enabled = enabled;
    }

    @Override
    public boolean enabled() {
        return enabled;
    }

    @Override
    public LiveRecommendationResponse generate(
            LiveSchemaSummary schema, QueryTelemetry telemetry, long slowQueryThresholdMs) {
        if (!enabled) {
            throw new IllegalStateException("AI recommendations are not enabled.");
        }
        if (apiKey.isBlank()) {
            throw new AiRecommendationException(
                    HttpStatus.SERVICE_UNAVAILABLE,
                    "Gemini recommendations are enabled but GEMINI_API_KEY is not configured.");
        }

        JsonNode response;
        try {
            String evidence = objectMapper.writeValueAsString(
                    AiRecommendationSupport.createEvidence(schema, telemetry, slowQueryThresholdMs));
            response = restClient.post()
                    .uri("/interactions")
                    .header("x-goog-api-key", apiKey)
                    .body(Map.of(
                            "model", model,
                            "input", evidence,
                            "system_instruction", AiRecommendationSupport.systemInstructions(),
                            "generation_config", Map.of(
                                    "temperature", 0.2,
                                    "max_output_tokens", 1200),
                            "response_format", AiRecommendationSupport.responseFormat()))
                    .retrieve()
                    .body(JsonNode.class);
        } catch (RestClientResponseException exception) {
            throw new AiRecommendationException(
                    HttpStatus.BAD_GATEWAY,
                    geminiFailureMessage(exception.getStatusCode().value(), exception));
        } catch (RestClientException exception) {
            throw new AiRecommendationException(
                    HttpStatus.BAD_GATEWAY, "Unable to reach the Google Gemini recommendation service.", exception);
        } catch (JsonProcessingException exception) {
            throw new IllegalStateException("Unable to prepare evidence for Gemini recommendations.", exception);
        }

        List<RecommendationSummary> recommendations =
                AiRecommendationSupport.parseGeminiResponse(response, objectMapper, schema);
        return new LiveRecommendationResponse(
                schema.databaseName(),
                recommendations,
                Instant.now(),
                false,
                "GEMINI",
                "AI-assisted recommendations were generated by Google Gemini from schema metadata and "
                        + "normalized query digests. Database credentials and query result rows are not sent. "
                        + "Suggestions are advisory and are never executed.");
    }

    private String geminiFailureMessage(int status, RestClientResponseException exception) {
        String providerMessage = providerErrorMessage(exception);
        String troubleshooting = switch (status) {
            case 400 -> "Check GEMINI_MODEL and the Gemini request configuration.";
            case 401, 403 -> "Check GEMINI_API_KEY, Gemini API access, and the selected Google AI Studio project.";
            case 404 -> "Check that GEMINI_MODEL is available for the Gemini API.";
            case 429 -> "Check your Google AI Studio model quota and rate limits.";
            default -> status >= 500
                    ? "Google Gemini may be temporarily unavailable."
                    : "Check the Gemini backend configuration.";
        };
        return "Google Gemini returned HTTP " + status + ". "
                + (providerMessage.isBlank() ? "" : providerMessage + " ")
                + troubleshooting;
    }

    private String providerErrorMessage(RestClientResponseException exception) {
        try {
            JsonNode error = objectMapper.readTree(exception.getResponseBodyAsString()).path("error");
            String message = error.path("message").asText("").replaceAll("[\\r\\n\\t]+", " ").trim();
            if (!apiKey.isBlank()) message = message.replace(apiKey, "[redacted]");
            if (message.length() > 300) message = message.substring(0, 300);
            String status = error.path("status").asText("").replaceAll("[^A-Za-z0-9_.-]", "");
            if (!status.isBlank() && !message.contains(status)) {
                return message.isBlank() ? "Provider error: " + status + "." : message + " (" + status + ").";
            }
            return message;
        } catch (JsonProcessingException exceptionDuringParsing) {
            return "";
        }
    }
}
