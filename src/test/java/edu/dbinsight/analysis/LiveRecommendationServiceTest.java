package edu.dbinsight.analysis;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.times;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import edu.dbinsight.api.ApiModels.IssueSummary;
import edu.dbinsight.api.ApiModels.LiveRecommendationResponse;
import edu.dbinsight.api.ApiModels.LiveSchemaSummary;
import edu.dbinsight.api.ApiModels.QuerySummary;
import edu.dbinsight.api.ApiModels.QueryTelemetry;
import edu.dbinsight.api.ApiModels.RecommendationSummary;
import java.time.Instant;
import java.util.List;
import org.junit.jupiter.api.Test;

class LiveRecommendationServiceTest {
    @Test
    void buildsAdvisoriesOnlyForObservedSchemaAndSlowQueryFindings() {
        List<IssueSummary> issues = List.of(
                new IssueSummary(1, "orders", "MISSING_PRIMARY_KEY", "No primary key was reported.", "MEDIUM", "OPEN"),
                new IssueSummary(2, "orders", "FOREIGN_KEY_WITHOUT_INDEX", "Foreign key fk_orders_customer lacks a leading index.", "MEDIUM", "OPEN"));
        List<QuerySummary> queries = List.of(
                new QuerySummary(1, "digest-slow", "SELECT * FROM orders WHERE customer_id = ?",
                    "dbinsight", "", 900, 25, 15000, 25, "SLOW", false),
                new QuerySummary(2, "digest-fast", "SELECT 1", "dbinsight", "", 1, 5, 0, 5, "HEALTHY", false));

        List<RecommendationSummary> results = LiveRecommendationService.fromEvidence(issues, queries, 500);

        assertEquals(3, results.size());
        assertTrue(results.get(0).title().contains("orders"));
        assertTrue(results.get(1).reason().contains("fk_orders_customer"));
        assertTrue(results.get(2).reason().contains("900.00 ms"));
        assertEquals("PENDING_REVIEW", results.get(2).status());
    }

    @Test
    void returnsNoRecommendationsWithoutFindings() {
        assertTrue(LiveRecommendationService.fromEvidence(List.of(), List.of(), 500).isEmpty());
    }

    @Test
    void buildsRuleBasedRecommendationsFromCurrentSchemaAndTelemetry() {
        SchemaAnalysisService schemaService = mock(SchemaAnalysisService.class);
        QueryTelemetryCollector telemetryCollector = mock(QueryTelemetryCollector.class);
        AiRecommendationGenerator aiGenerator = mock(AiRecommendationGenerator.class);
        LiveSchemaSummary schema = new LiveSchemaSummary(
                "shop", List.of(), List.of(new IssueSummary(7, "orders", "MISSING_PRIMARY_KEY",
                        "No primary key was reported.", "MEDIUM", "OPEN")), Instant.now(), false);
        QueryTelemetry telemetry = new QueryTelemetry(
                List.of(), "shop", false, "Unavailable", Instant.now(), 500, 0, false, false);
        when(schemaService.analyze(3L)).thenReturn(schema);
        when(telemetryCollector.snapshot(3L)).thenReturn(telemetry);
        when(aiGenerator.enabled()).thenReturn(false);

        LiveRecommendationResponse response =
                new LiveRecommendationService(schemaService, telemetryCollector, aiGenerator, 500, 300_000)
                        .recommendations(3L);

        assertEquals("RULE_BASED", response.source());
        assertEquals(1, response.recommendations().size());
        assertEquals(
                "Rule-based suggestions use current JDBC metadata and Performance Schema summaries.",
                response.message());
        verify(aiGenerator, never()).generate(schema, telemetry, 500);
    }

    @Test
    void usesAndCachesGeminiRecommendationsWhenEnabledAndFindingsExist() {
        SchemaAnalysisService schemaService = mock(SchemaAnalysisService.class);
        QueryTelemetryCollector telemetryCollector = mock(QueryTelemetryCollector.class);
        AiRecommendationGenerator aiGenerator = mock(AiRecommendationGenerator.class);
        LiveSchemaSummary schema = new LiveSchemaSummary(
                "shop", List.of(), List.of(new IssueSummary(7, "orders", "MISSING_PRIMARY_KEY",
                        "No primary key was reported.", "MEDIUM", "OPEN")), Instant.now(), false);
        QueryTelemetry telemetry = new QueryTelemetry(
                List.of(), "shop", false, "Unavailable", Instant.now(), 500, 0, false, false);
        LiveRecommendationResponse aiResponse = new LiveRecommendationResponse(
                "shop",
                List.of(new RecommendationSummary(1, 7L, "Review orders", "Evidence-based advice",
                        "MEDIUM", "PENDING_REVIEW")),
                Instant.now(),
                false,
                "GEMINI",
                "AI-assisted recommendations were generated by Gemini.");
        when(schemaService.analyze(3L)).thenReturn(schema);
        when(telemetryCollector.snapshot(3L)).thenReturn(telemetry);
        when(aiGenerator.enabled()).thenReturn(true);
        when(aiGenerator.generate(schema, telemetry, 500)).thenReturn(aiResponse);

        LiveRecommendationService service =
                new LiveRecommendationService(schemaService, telemetryCollector, aiGenerator, 500, 300_000);
        LiveRecommendationResponse response = service.recommendations(3L);
        LiveRecommendationResponse cachedResponse = service.recommendations(3L);

        assertEquals("GEMINI", response.source());
        assertEquals(response, cachedResponse);
        verify(aiGenerator).generate(schema, telemetry, 500);
    }

    @Test
    void doesNotCallGeminiWithoutActionableEvidence() {
        SchemaAnalysisService schemaService = mock(SchemaAnalysisService.class);
        QueryTelemetryCollector telemetryCollector = mock(QueryTelemetryCollector.class);
        AiRecommendationGenerator aiGenerator = mock(AiRecommendationGenerator.class);
        LiveSchemaSummary schema =
                new LiveSchemaSummary("shop", List.of(), List.of(), Instant.now(), false);
        QueryTelemetry telemetry = new QueryTelemetry(
                List.of(), "shop", false, "No query data", Instant.now(), 500, 0, false, false);
        when(schemaService.analyze(3L)).thenReturn(schema);
        when(telemetryCollector.snapshot(3L)).thenReturn(telemetry);
        when(aiGenerator.enabled()).thenReturn(true);

        LiveRecommendationResponse response =
                new LiveRecommendationService(schemaService, telemetryCollector, aiGenerator, 500, 300_000)
                        .recommendations(3L);

        assertEquals("RULE_BASED", response.source());
        assertTrue(response.recommendations().isEmpty());
        verify(aiGenerator, never()).generate(schema, telemetry, 500);
    }

    @Test
    void doesNotCacheRecommendationsWithoutAnExplicitDatabaseId() {
        SchemaAnalysisService schemaService = mock(SchemaAnalysisService.class);
        QueryTelemetryCollector telemetryCollector = mock(QueryTelemetryCollector.class);
        AiRecommendationGenerator aiGenerator = mock(AiRecommendationGenerator.class);
        LiveSchemaSummary schema = new LiveSchemaSummary(
                "shop", List.of(), List.of(new IssueSummary(7, "orders", "MISSING_PRIMARY_KEY",
                        "No primary key was reported.", "MEDIUM", "OPEN")), Instant.now(), false);
        QueryTelemetry telemetry = new QueryTelemetry(
                List.of(), "shop", false, "Unavailable", Instant.now(), 500, 0, false, false);
        LiveRecommendationResponse aiResponse = new LiveRecommendationResponse(
                "shop", List.of(), Instant.now(), false, "GEMINI", "Generated by Gemini.");
        when(schemaService.analyze((Long) null)).thenReturn(schema);
        when(telemetryCollector.snapshot(null)).thenReturn(telemetry);
        when(aiGenerator.enabled()).thenReturn(true);
        when(aiGenerator.generate(schema, telemetry, 500)).thenReturn(aiResponse);
        LiveRecommendationService service =
                new LiveRecommendationService(schemaService, telemetryCollector, aiGenerator, 500, 300_000);

        service.recommendations();
        service.recommendations();

        verify(aiGenerator, times(2)).generate(schema, telemetry, 500);
    }
}